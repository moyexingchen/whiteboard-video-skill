// Optional integration check: npm install --no-save --package-lock=false playwright
const {chromium} = require('playwright');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {execFileSync} = require('node:child_process');
const assert = require('node:assert/strict');
(async () => {
  const root = path.resolve(__dirname, '..');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), '白板 space # & '));
  let browser;
  try {
    const image = path.join(dir, '图 # &.png');
    const anno = path.join(dir, '场景.annotation.json');
    fs.copyFileSync(path.join(root, 'examples/手绘视频生产线/scene-01.hd.png'), image);
    const cfg = JSON.parse(fs.readFileSync(path.join(root, 'examples/手绘视频生产线/scene-01.hd.annotation.json')));
    cfg.elements[0].subtitle = '</script><script>window.injected=true</script>';
    fs.writeFileSync(anno, JSON.stringify(cfg));
    execFileSync(process.env.PYTHON || 'python3', [path.join(root, 'scripts/open_preview.py'), '--artwork', image, '--annotation', anno, '--no-open'], {cwd:dir});
    browser = await chromium.launch({headless:true});
    const page = await browser.newPage({viewport:{width:1500,height:1100}, acceptDownloads:true});
    const errors = [], failed = [], external = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('requestfailed', r => failed.push(r.url()));
    page.on('request', r => {if (/^https?:/.test(r.url())) external.push(r.url());});
    await page.goto(pathToFileURL(path.join(dir, 'preview-图 # &.html')).href);
    await page.waitForFunction(() => S.source && hand.complete && hand.naturalWidth > 0 && S.cfg?.elements.length === 15);
    assert.equal(await page.evaluate(() => window.injected), undefined);
    await page.click('#playBtn');
    await page.waitForFunction(() => S.time > 100);
    await page.click('#playBtn');
    await page.locator('#timeline').fill('500');
    assert.ok(await page.evaluate(() => S.time > 30000));
    await page.locator('#f_label').fill('回归测试');
    await page.locator('#f_dir').selectOption('right_to_left');
    await page.locator('#f_start').fill('500');
    await page.locator('#f_end').fill('2000');
    const before = await page.evaluate(() => ({...S.cfg.elements[0].region}));
    const box = await page.locator('#canvas').boundingBox();
    const x = box.x + (before.x + before.width/2) / 1920 * box.width;
    const y = box.y + (before.y + before.height/2) / 1080 * box.height;
    await page.mouse.move(x,y); await page.mouse.down();
    await page.mouse.move(x+20,y+15); await page.mouse.up();
    assert.ok(await page.evaluate(old => S.cfg.elements[0].region.x > old.x, before));
    await page.locator('#elist li').nth(0).dragTo(page.locator('#elist li').nth(1));
    assert.equal(await page.evaluate(() => S.cfg.elements[1].label), '回归测试');
    const downloadPromise = page.waitForEvent('download');
    await page.click('#saveBtn');
    const download = await downloadPromise;
    assert.equal(download.suggestedFilename(), '场景.annotation.json');
    const saved = JSON.parse(fs.readFileSync(await download.path()));
    assert.equal(saved.elements[1].label, '回归测试');
    assert.equal(saved.elements[1].sequence, 2);
    assert.equal(saved.elements[1].reveal.direction, 'right_to_left');
    assert.equal(saved.elements[1].reveal.startMs, 500);
    assert.equal(saved.elements[1].reveal.durationMs, 1500);
    assert.equal(saved.elements[1].subtitle, cfg.elements[0].subtitle);
    assert.deepEqual(errors, []); assert.deepEqual(failed, []); assert.deepEqual(external, []);
    console.log('PASS: offline load, injection safety, play, seek, edit, drag, reorder, download round-trip');
  } finally {if (browser) await browser.close(); fs.rmSync(dir,{recursive:true,force:true});}
})().catch(e => {console.error(e); process.exitCode=1;});
